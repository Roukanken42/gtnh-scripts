-- Which modules the controller is allowed to aim: AUTO or MANUAL, per module,
-- remembered across runs.
--
-- AUTO is the default, and the default has to be AUTO -- a fleet that does nothing
-- until every module has been switched on by hand is not automatic. But that makes
-- the memory necessary rather than a nicety: a module you deliberately set yourself
-- would go back to being driven by the controller the moment it restarted, which is
-- the one thing MANUAL exists to prevent. So the exceptions are written down.
--
-- Only the MANUAL ones are stored. The file is then a list of "leave these alone",
-- a new module is AUTO because nothing says otherwise, and deleting the file resets
-- the fleet to fully automatic -- all three of which are the behaviour you would
-- guess from the outside.
--
-- The file lives beside data/stations.lua and for the same reason: machine-specific
-- state that the repo has no business carrying. The two are deliberately separate
-- files -- `setup` rewrites its one wholesale, and doing that to a fleet's modes
-- would silently seize every module the player had taken control of.

local modes = {}

modes.AUTO = "AUTO"
modes.MANUAL = "MANUAL"

modes.MODULE = "data.modes"
modes.DIR = "data"
modes.FILE = "data/modes.lua"

-- ---- pure ------------------------------------------------------------------

-- A module's mode. Anything not written down is AUTO.
function modes.of(map, addr)
    if type(map) == "table" and map[addr] == modes.MANUAL then return modes.MANUAL end
    return modes.AUTO
end

function modes.isAuto(map, addr)
    return modes.of(map, addr) == modes.AUTO
end

-- Sets a mode, returning true if it actually changed -- so a caller knows whether
-- there is anything to write to disk or say in the log.
function modes.set(map, addr, mode)
    local want = (mode == modes.MANUAL) and modes.MANUAL or modes.AUTO
    local had = modes.of(map, addr)
    if had == want then return false end
    -- AUTO is stored as absence, not as a string: see the header.
    map[addr] = (want == modes.MANUAL) and modes.MANUAL or nil
    return true
end

-- Marks a module MANUAL because the player has just set something on it. Separate
-- from `set` only so the intent reads clearly at the call sites, which are the
-- three places a human can change a module: an edit, a paste, and the advisor.
function modes.claim(map, addr)
    return modes.set(map, addr, modes.MANUAL)
end

function modes.count(map, fleet)
    local auto, manual = 0, 0
    for _, addr in ipairs(fleet or {}) do
        if modes.isAuto(map, addr) then auto = auto + 1 else manual = manual + 1 end
    end
    return auto, manual
end

-- ---- persistence -----------------------------------------------------------

-- What the last run left behind, as { [address] = "MANUAL" }. A machine that has
-- never had a module switched to MANUAL has no file, which is not an error.
function modes.load()
    local ok, data = pcall(require, modes.MODULE)
    if not ok or type(data) ~= "table" then return {} end
    local out = {}
    for addr, mode in pairs(data) do
        if type(addr) == "string" and mode == modes.MANUAL then out[addr] = modes.MANUAL end
    end
    return out
end

-- Writes the MANUAL set back. Returns the path, or nil + error -- and a caller is
-- expected to carry on either way: losing the file costs one setting after a
-- restart, while refusing to run because a disk is full costs a fleet.
function modes.save(map, cwd)
    local okSer, serialization = pcall(require, "serialization")
    local okFs, filesystem = pcall(require, "filesystem")
    local okSh, shell = pcall(require, "shell")
    if not (okSer and okFs and okSh) then return nil, "no filesystem (off-machine?)" end

    local payload = {}
    for addr, mode in pairs(map or {}) do
        if mode == modes.MANUAL then payload[addr] = modes.MANUAL end
    end

    local base = cwd or shell.getWorkingDirectory()
    local dir = filesystem.concat(base, modes.DIR)
    if not filesystem.exists(dir) then filesystem.makeDirectory(dir) end

    local path = filesystem.concat(base, modes.FILE)
    local text = table.concat({
        "-- Generated by mining/main.lua: the modules the controller must NOT aim.",
        "-- Anything absent is AUTO. Safe to delete -- that resets the fleet to",
        "-- fully automatic. NOT part of the repo/manifest.",
        "return " .. serialization.serialize(payload),
        "",
    }, "\n")

    local f, ferr = io.open(path, "w")
    if not f then return nil, tostring(ferr) end
    f:write(text)
    f:close()
    return path
end

return modes
