# Regenerates the `manifest` file that install.lua reads.
#
# Walks the repo and lists every *.lua file that should be deployed to an
# OpenComputers machine. Run this from anywhere before committing whenever you
# add, remove, or rename a script:
#
#     pwsh ./tools/build-manifest.ps1
#
# Rules:
#   - Only *.lua files are included (docs, images, tooling, etc. are skipped).
#   - Files under excluded top-level folders (.git, tools, docs) are skipped.
#   - Any file named `config.lua` (or *.config.lua), plus anything listed in
#     $userOwned below, is written with a leading `? ` marker, so install.lua will
#     NOT overwrite a machine's local copy. Those are the files a player edits:
#     losing one to an update would lose their settings, or in wants.lua's case the
#     entire description of what their fleet is for.

$ErrorActionPreference = "Stop"

# Repo root = parent of the folder this script lives in.
$repoRoot = Split-Path -Parent $PSScriptRoot
$excludedTopDirs = @(".git", "tools", "docs")

# Repo-relative paths the player owns, beyond the config.lua naming rule.
$userOwned = @("mining/wants.lua")

$files = Get-ChildItem -Path $repoRoot -Recurse -File -Filter *.lua |
    ForEach-Object {
        # Path relative to repo root, using forward slashes.
        $rel = $_.FullName.Substring($repoRoot.Length + 1) -replace "\\", "/"
        $rel
    } |
    Where-Object {
        $top = ($_ -split "/")[0]
        $excludedTopDirs -notcontains $top
    } |
    Sort-Object

$lines = @(
    "# Auto-generated by tools/build-manifest.ps1 - do not edit by hand."
    "# Lists every file install.lua downloads onto an OpenComputers machine."
    ""
)

foreach ($rel in $files) {
    $name = ($rel -split "/")[-1]
    if ($name -eq "config.lua" -or $name -like "*.config.lua" -or $userOwned -contains $rel) {
        $lines += "? $rel"
    } else {
        $lines += $rel
    }
}

$manifestPath = Join-Path $repoRoot "manifest"
# Write LF line endings, no BOM - keeps the file clean for OC's parser.
$content = ($lines -join "`n") + "`n"
[System.IO.File]::WriteAllText($manifestPath, $content, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "Wrote $($files.Count) file(s) to $manifestPath"